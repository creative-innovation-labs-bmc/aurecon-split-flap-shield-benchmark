import { chromium } from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:3840,height:804}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:8000/c-canvas-2560.html?bench=1&build=c3',{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__canvasCHealth&&window.CanvasBench?.textGeometry,{timeout:10000});
await page.waitForTimeout(8700);
const before=await page.evaluate(()=>({...window.__canvasCHealth,geom:window.CanvasBench.textGeometry}));
await page.waitForTimeout(700);
const mid1=await page.evaluate(()=>({...window.__canvasCHealth}));
await page.screenshot({path:'qc/c3-office-motion-mid.png'});
await page.waitForTimeout(700);
const mid2=await page.evaluate(()=>({...window.__canvasCHealth}));
await page.waitForTimeout(1200);
const after=await page.evaluate(()=>({...window.__canvasCHealth,active:window.BenchRuntime.getRenderer().activeCount()}));
const textFrames1=mid1.textAnimatedCellDraws-before.textAnimatedCellDraws;
const textFrames2=mid2.textAnimatedCellDraws-mid1.textAnimatedCellDraws;
const centreError=Math.abs(before.geom.visualCentre-45);
const report={passed:false,checks:{textMovesAcrossFirstWindow:textFrames1>5,textMovesAcrossSecondWindow:textFrames2>5,officeTransitionDrains:after.active===0,centredSmallText:centreError<0.01,noErrors:errors.length===0},details:{before,mid1,mid2,after,textFrames1,textFrames2,centreError,errors}};
report.passed=Object.values(report.checks).every(Boolean);fs.mkdirSync('qc',{recursive:true});fs.writeFileSync('qc/c3-office-motion-report.json',JSON.stringify(report,null,2)+'\n');await browser.close();if(!report.passed)process.exitCode=1;